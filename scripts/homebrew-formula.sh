#!/bin/sh
# Prints the Homebrew formula for one release to stdout: the compiled binaries, so brew users need no Bun.
# The release job pushes it to sustinbebustin/homebrew-tap as `Formula/hush.rb`.
# Usage: `sh scripts/homebrew-formula.sh <version> <SHA256SUMS>`, e.g. `sh scripts/homebrew-formula.sh 0.1.0 dist/SHA256SUMS`.
set -eu

if [ $# -ne 2 ]; then
  echo "homebrew-formula: expected <version> <SHA256SUMS>, got $# arguments" >&2
  exit 1
fi
version=$1
sums=$2

sha() {
  sum=$(awk -v file="hush-$1" '$2 == file { print $1 }' "$sums")
  if [ -z "$sum" ]; then
    echo "homebrew-formula: $sums has no checksum for hush-$1; build every target before generating the formula" >&2
    exit 1
  fi
  echo "$sum"
}

# Each `sha` runs before the heredoc so a missing checksum stops the script instead of printing an empty one.
darwin_arm64=$(sha darwin-arm64)
darwin_x64=$(sha darwin-x64)
linux_arm64=$(sha linux-arm64)
linux_x64=$(sha linux-x64)
base="https://github.com/sustinbebustin/hush/releases/download/v$version"

cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/homebrew-formula.sh in sustinbebustin/hush on each release. Do not edit.
class Hush < Formula
  desc "Secret store that lets coding agents use secrets without seeing them"
  homepage "https://github.com/sustinbebustin/hush"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/hush-darwin-arm64"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/hush-darwin-x64"
      sha256 "$darwin_x64"
    end
  end

  on_linux do
    on_arm do
      url "$base/hush-linux-arm64"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/hush-linux-x64"
      sha256 "$linux_x64"
    end
  end

  def install
    bin.install Dir["hush-*"].first => "hush"
  end

  test do
    assert_equal "hush v#{version}", shell_output("#{bin}/hush --version").strip
  end
end
EOF
